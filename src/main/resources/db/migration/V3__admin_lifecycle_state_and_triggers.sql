-- H-04: estado singleton de lifecycle de ADMIN, auditoria administrativa,
-- triggers de contagem e proteção do último ADMIN.
-- Owner: arena_migrator (Flyway). Executa como uma única transação.

-- Chave fixa e documentada do advisory transaction lock do lifecycle de ADMIN.
-- Todas as operações de perfil/bootstrap/recovery/reconcile e as triggers de
-- statement em public.usuario usam a mesma chave.
CREATE OR REPLACE FUNCTION public.h04_admin_lifecycle_lock_key()
RETURNS BIGINT
LANGUAGE sql
IMMUTABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT 7409395520021::BIGINT;
$$;

REVOKE EXECUTE ON FUNCTION public.h04_admin_lifecycle_lock_key() FROM PUBLIC;

-- ---------------------------------------------------------------------------
-- Tabela singleton de estado
-- ---------------------------------------------------------------------------
CREATE TABLE public.admin_lifecycle_state (
    singleton_id SMALLINT PRIMARY KEY CHECK (singleton_id = 1),
    admin_count BIGINT NOT NULL CHECK (admin_count >= 0),
    bootstrap_consumed BOOLEAN NOT NULL DEFAULT false,
    bootstrap_consumed_at TIMESTAMPTZ,
    recovery_required BOOLEAN NOT NULL DEFAULT false,
    last_recovery_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),

    -- Coerência do marcador e seu timestamp
    CONSTRAINT ck_admin_lifecycle_state_bootstrap_coherent
        CHECK (
            (bootstrap_consumed = false AND bootstrap_consumed_at IS NULL)
            OR (bootstrap_consumed = true AND bootstrap_consumed_at IS NOT NULL)
        )
);

-- Índice redundante mas explícito para acesso pelo singleton_id=1.
CREATE UNIQUE INDEX ix_admin_lifecycle_state_singleton
    ON public.admin_lifecycle_state (singleton_id);

-- ---------------------------------------------------------------------------
-- Tabela de auditoria administrativa (append-only)
-- ---------------------------------------------------------------------------
CREATE TABLE public.admin_audit_event (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    operation VARCHAR(32) NOT NULL
        CHECK (operation IN (
            'BOOTSTRAP', 'RECOVERY', 'PROMOTE', 'DEMOTE',
            'ADMIN_DELETE', 'PASSWORD_RESET', 'PASSWORD_CHANGE', 'RECONCILE'
        )),
    outcome VARCHAR(16) NOT NULL
        CHECK (outcome IN ('SUCCEEDED', 'REJECTED')),
    source VARCHAR(32) NOT NULL
        CHECK (source IN (
            'HTTP', 'BOOTSTRAP_CLI', 'RECOVERY_CLI', 'RECONCILE_CLI', 'DB_DIRECT'
        )),
    actor_type VARCHAR(16)
        CHECK (actor_type IN ('USER', 'OPERATOR', 'DATABASE')),
    actor_user_id BIGINT,
    actor_ref VARCHAR(255),
    target_user_id BIGINT,
    target_email_snapshot VARCHAR(255),
    profile_before VARCHAR(16)
        CHECK (profile_before IN ('ADMIN', 'CLIENTE')),
    profile_after VARCHAR(16)
        CHECK (profile_after IN ('ADMIN', 'CLIENTE')),
    reason TEXT,
    change_ticket VARCHAR(128),
    request_id VARCHAR(128),
    error_code VARCHAR(64)
);

CREATE INDEX ix_admin_audit_event_occurred_at
    ON public.admin_audit_event (occurred_at, event_id);
CREATE INDEX ix_admin_audit_event_actor
    ON public.admin_audit_event (actor_user_id, occurred_at);
CREATE INDEX ix_admin_audit_event_target
    ON public.admin_audit_event (target_user_id, occurred_at);
CREATE INDEX ix_admin_audit_event_operation
    ON public.admin_audit_event (operation, occurred_at);

-- ---------------------------------------------------------------------------
-- Inicialização do estado (backfill) sob lock exclusivo em usuario.
-- Placeholder ${h04InitialInstall} deve ser 'true' apenas quando o pipeline
-- puder afirmar que o destino é uma instalação nova e ainda vazia.
-- ---------------------------------------------------------------------------
DO $$
DECLARE
    v_admin_count BIGINT;
    v_user_count BIGINT;
    v_initial_install BOOLEAN := '${h04InitialInstall}' = 'true';
BEGIN
    LOCK TABLE public.usuario IN ACCESS EXCLUSIVE MODE;

    SELECT COUNT(*) INTO v_admin_count
    FROM public.usuario
    WHERE perfil = 'ADMIN';

    SELECT COUNT(*) INTO v_user_count
    FROM public.usuario;

    IF v_initial_install AND v_user_count > 0 THEN
        RAISE EXCEPTION
            'H-04 initial install flag is true but usuario table already contains % row(s)',
            v_user_count;
    END IF;

    IF v_initial_install THEN
        -- PENDING: sem ADMIN, sem usuários, bootstrap ainda não consumido.
        INSERT INTO public.admin_lifecycle_state (
            singleton_id, admin_count, bootstrap_consumed, bootstrap_consumed_at,
            recovery_required, last_recovery_at, updated_at
        ) VALUES (
            1, 0, false, NULL, false, NULL, statement_timestamp()
        );
    ELSIF v_admin_count = 0 THEN
        -- Legado sem ADMIN: bootstrap já fechado, recovery necessária.
        INSERT INTO public.admin_lifecycle_state (
            singleton_id, admin_count, bootstrap_consumed, bootstrap_consumed_at,
            recovery_required, last_recovery_at, updated_at
        ) VALUES (
            1, 0, true, statement_timestamp(), true, NULL, statement_timestamp()
        );
    ELSE
        -- Legado com ADMIN: bootstrap fechado, estado ativo.
        INSERT INTO public.admin_lifecycle_state (
            singleton_id, admin_count, bootstrap_consumed, bootstrap_consumed_at,
            recovery_required, last_recovery_at, updated_at
        ) VALUES (
            1, v_admin_count, true, statement_timestamp(), false, NULL, statement_timestamp()
        );
    END IF;
END $$;

-- ---------------------------------------------------------------------------
-- Função auxiliar: atualização atômica do contador.
-- Incremento sempre permitido. Decremento só quando o resultado mantém pelo
-- menos 1 ADMIN (estado CONSUMED/ativo).
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.h04_update_admin_count(p_delta BIGINT)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF p_delta > 0 THEN
        UPDATE public.admin_lifecycle_state
        SET admin_count = admin_count + p_delta,
            updated_at = statement_timestamp()
        WHERE singleton_id = 1;
    ELSIF p_delta < 0 THEN
        UPDATE public.admin_lifecycle_state
        SET admin_count = admin_count + p_delta,
            updated_at = statement_timestamp()
        WHERE singleton_id = 1
          AND admin_count + p_delta >= 1;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'H-04 last admin protection: cannot reduce admin_count below 1';
        END IF;
    END IF;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.h04_update_admin_count(BIGINT) FROM PUBLIC;

-- ---------------------------------------------------------------------------
-- Trigger AFTER ROW em public.usuario: aplica o delta real no contador.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.h04_trg_usuario_admin_count_row()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_delta BIGINT := 0;
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.perfil = 'ADMIN' THEN
            v_delta := 1;
        END IF;
    ELSIF TG_OP = 'UPDATE' THEN
        IF OLD.perfil = 'CLIENTE' AND NEW.perfil = 'ADMIN' THEN
            v_delta := 1;
        ELSIF OLD.perfil = 'ADMIN' AND NEW.perfil = 'CLIENTE' THEN
            v_delta := -1;
        END IF;
    ELSIF TG_OP = 'DELETE' THEN
        IF OLD.perfil = 'ADMIN' THEN
            v_delta := -1;
        END IF;
    END IF;

    IF v_delta <> 0 THEN
        PERFORM public.h04_update_admin_count(v_delta);
    END IF;

    RETURN COALESCE(NEW, OLD);
END;
$$;

REVOKE EXECUTE ON FUNCTION public.h04_trg_usuario_admin_count_row() FROM PUBLIC;

