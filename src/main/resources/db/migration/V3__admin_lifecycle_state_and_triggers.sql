-- ---------------------------------------------------------------------------
-- Função helper única para consumir o marcador de bootstrap.
-- Só pode ser chamada por bootstrap_first_admin ou reconcile autorizado.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.h04_consume_bootstrap_marker()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    UPDATE public.admin_lifecycle_state
    SET bootstrap_consumed = true,
        bootstrap_consumed_at = statement_timestamp(),
        updated_at = statement_timestamp()
    WHERE singleton_id = 1
      AND bootstrap_consumed = false;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'H-04 bootstrap marker is already consumed or state is missing';
    END IF;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.h04_consume_bootstrap_marker() FROM PUBLIC;

-- ---------------------------------------------------------------------------
-- Bootstrap: cria o primeiro ADMIN e consome o marcador.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.h04_bootstrap_first_admin(
    p_nome VARCHAR(255),
    p_email VARCHAR(255),
    p_telefone VARCHAR(255),
    p_senha_hash VARCHAR(255)
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_state public.admin_lifecycle_state%ROWTYPE;
    v_user_id BIGINT;
BEGIN
    PERFORM pg_advisory_xact_lock(public.h04_admin_lifecycle_lock_key());

    SELECT * INTO v_state
    FROM public.admin_lifecycle_state
    WHERE singleton_id = 1
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'H-04 admin lifecycle state is missing';
    END IF;

    IF v_state.recovery_required THEN
        RAISE EXCEPTION 'H-04 cannot bootstrap while recovery is required';
    END IF;

    IF v_state.bootstrap_consumed THEN
        RAISE EXCEPTION 'H-04 bootstrap already consumed';
    END IF;

    IF v_state.admin_count <> 0 THEN
        RAISE EXCEPTION 'H-04 bootstrap requires admin_count=0';
    END IF;

    IF EXISTS (SELECT 1 FROM public.usuario WHERE perfil = 'ADMIN') THEN
        RAISE EXCEPTION 'H-04 bootstrap requires zero real admins';
    END IF;

    INSERT INTO public.usuario (nome, email, telefone, senha, perfil)
    VALUES (p_nome, p_email, p_telefone, p_senha_hash, 'ADMIN')
    RETURNING id INTO v_user_id;

    PERFORM public.h04_consume_bootstrap_marker();

    PERFORM public.h04_append_audit_event(
        'BOOTSTRAP', 'SUCCEEDED', 'BOOTSTRAP_CLI',
        'OPERATOR', NULL, 'bootstrap-cli',
        v_user_id, p_email, NULL, 'ADMIN',
        NULL, NULL, NULL, NULL
    );

    RETURN v_user_id;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.h04_bootstrap_first_admin(
    VARCHAR(255), VARCHAR(255), VARCHAR(255), VARCHAR(255)
) FROM PUBLIC;

-- ---------------------------------------------------------------------------
-- Recovery: restaura um ADMIN quando recovery_required=true.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.h04_recover_admin(
    p_user_id BIGINT,
    p_nome VARCHAR(255),
    p_email VARCHAR(255),
    p_telefone VARCHAR(255),
    p_senha_hash VARCHAR(255)
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_state public.admin_lifecycle_state%ROWTYPE;
    v_existing_profile VARCHAR(16);
    v_target_id BIGINT;
BEGIN
    PERFORM pg_advisory_xact_lock(public.h04_admin_lifecycle_lock_key());

    SELECT * INTO v_state
    FROM public.admin_lifecycle_state
    WHERE singleton_id = 1
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'H-04 admin lifecycle state is missing';
    END IF;

    IF NOT v_state.bootstrap_consumed THEN
        RAISE EXCEPTION 'H-04 recovery requires bootstrap consumed; use bootstrap';
    END IF;

    IF NOT v_state.recovery_required THEN
        RAISE EXCEPTION 'H-04 recovery requires recovery_required=true; use reconcile';
    END IF;

    IF v_state.admin_count <> 0 THEN
        RAISE EXCEPTION 'H-04 recovery requires admin_count=0';
    END IF;

    IF EXISTS (SELECT 1 FROM public.usuario WHERE perfil = 'ADMIN') THEN
        RAISE EXCEPTION 'H-04 recovery requires zero real admins';
    END IF;

    IF p_user_id IS NOT NULL THEN
        SELECT perfil INTO v_existing_profile
        FROM public.usuario
        WHERE id = p_user_id;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'H-04 recovery target user % not found', p_user_id;
        END IF;

        UPDATE public.usuario
        SET perfil = 'ADMIN'
        WHERE id = p_user_id;

        v_target_id := p_user_id;

        PERFORM public.h04_append_audit_event(
            'RECOVERY', 'SUCCEEDED', 'RECOVERY_CLI',
            'OPERATOR', NULL, 'recovery-cli',
            v_target_id, p_email, v_existing_profile, 'ADMIN',
            NULL, NULL, NULL, NULL
        );
    ELSE
        INSERT INTO public.usuario (nome, email, telefone, senha, perfil)
        VALUES (p_nome, p_email, p_telefone, p_senha_hash, 'ADMIN')
        RETURNING id INTO v_target_id;

        PERFORM public.h04_append_audit_event(
            'RECOVERY', 'SUCCEEDED', 'RECOVERY_CLI',
            'OPERATOR', NULL, 'recovery-cli',
            v_target_id, p_email, NULL, 'ADMIN',
            NULL, NULL, NULL, NULL
        );
    END IF;

    UPDATE public.admin_lifecycle_state
    SET recovery_required = false,
        last_recovery_at = statement_timestamp(),
        updated_at = statement_timestamp()
    WHERE singleton_id = 1;

    RETURN v_target_id;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.h04_recover_admin(
    BIGINT, VARCHAR(255), VARCHAR(255), VARCHAR(255), VARCHAR(255)
) FROM PUBLIC;

-- ---------------------------------------------------------------------------
-- Reconcile: corrige contador/marcadores sem criar/apagar usuário.
-- Só deve ser executado offline, autorizado e auditado.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.h04_reconcile_admin_state(
    p_reason TEXT
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_state public.admin_lifecycle_state%ROWTYPE;
    v_real_count BIGINT;
BEGIN
    PERFORM pg_advisory_xact_lock(public.h04_admin_lifecycle_lock_key());

    SELECT * INTO v_state
    FROM public.admin_lifecycle_state
    WHERE singleton_id = 1
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'H-04 admin lifecycle state is missing';
    END IF;

    SELECT COUNT(*) INTO v_real_count
    FROM public.usuario
    WHERE perfil = 'ADMIN';

    IF v_state.admin_count = v_real_count
       AND (
           (v_real_count = 0 AND v_state.recovery_required)
           OR (v_real_count > 0 AND NOT v_state.recovery_required)
       )
       AND (
           (v_real_count = 0 AND NOT v_state.bootstrap_consumed)
           OR (v_real_count > 0 AND v_state.bootstrap_consumed)
       )
    THEN
        -- Estado já consistente; apenas registra reconcile sem mutação.
        PERFORM public.h04_append_audit_event(
            'RECONCILE', 'SUCCEEDED', 'RECONCILE_CLI',
            'OPERATOR', NULL, 'reconcile-cli',
            NULL, NULL, NULL, NULL,
            p_reason, NULL, NULL, NULL
        );
        RETURN;
    END IF;

    UPDATE public.admin_lifecycle_state
    SET admin_count = v_real_count,
        bootstrap_consumed = CASE
            WHEN v_real_count > 0 AND NOT bootstrap_consumed THEN true
            ELSE bootstrap_consumed
        END,
        bootstrap_consumed_at = CASE
            WHEN v_real_count > 0 AND bootstrap_consumed_at IS NULL THEN statement_timestamp()
            ELSE bootstrap_consumed_at
        END,
        recovery_required = CASE
            WHEN v_real_count = 0 AND bootstrap_consumed THEN true
            WHEN v_real_count > 0 THEN false
            ELSE recovery_required
        END,
        last_recovery_at = last_recovery_at,
        updated_at = statement_timestamp()
    WHERE singleton_id = 1;

    PERFORM public.h04_append_audit_event(
        'RECONCILE', 'SUCCEEDED', 'RECONCILE_CLI',
        'OPERATOR', NULL, 'reconcile-cli',
        NULL, NULL, NULL, NULL,
        p_reason, NULL, NULL, NULL
    );
END;
$$;

