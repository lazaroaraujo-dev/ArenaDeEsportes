-- ---------------------------------------------------------------------------
-- Validação transacional diferida (DEFERRABLE INITIALLY DEFERRED).
-- Garante que nenhum commit deixe o estado em combinação inconsistente.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.h04_trg_validate_admin_lifecycle_state()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_state public.admin_lifecycle_state%ROWTYPE;
    v_real_count BIGINT;
BEGIN
    SELECT * INTO v_state
    FROM public.admin_lifecycle_state
    WHERE singleton_id = 1;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'H-04 admin lifecycle state is missing';
    END IF;

    SELECT COUNT(*) INTO v_real_count
    FROM public.usuario
    WHERE perfil = 'ADMIN';

    IF v_state.admin_count <> v_real_count THEN
        RAISE EXCEPTION
            'H-04 admin_count (%) diverges from real admin count (%)',
            v_state.admin_count, v_real_count;
    END IF;

    IF v_state.bootstrap_consumed = false AND v_state.recovery_required = false THEN
        -- PENDING
        IF v_state.admin_count <> 0 OR v_real_count <> 0 THEN
            RAISE EXCEPTION 'H-04 PENDING state requires zero admins';
        END IF;
    ELSIF v_state.bootstrap_consumed = true AND v_state.recovery_required = true THEN
        -- RECOVERY_REQUIRED
        IF v_state.admin_count <> 0 OR v_real_count <> 0 THEN
            RAISE EXCEPTION 'H-04 RECOVERY_REQUIRED state requires zero admins';
        END IF;
    ELSIF v_state.bootstrap_consumed = true AND v_state.recovery_required = false THEN
        -- CONSUMED/ativo
        IF v_state.admin_count < 1 OR v_real_count < 1 THEN
            RAISE EXCEPTION 'H-04 CONSUMED state requires at least one admin';
        END IF;
    ELSE
        RAISE EXCEPTION
            'H-04 invalid state combination: bootstrap_consumed=%, recovery_required=%',
            v_state.bootstrap_consumed, v_state.recovery_required;
    END IF;

    RETURN NULL;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.h04_trg_validate_admin_lifecycle_state() FROM PUBLIC;

CREATE CONSTRAINT TRIGGER trg_h04_validate_admin_lifecycle_state
    AFTER INSERT OR UPDATE OR DELETE ON public.usuario
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION public.h04_trg_validate_admin_lifecycle_state();

