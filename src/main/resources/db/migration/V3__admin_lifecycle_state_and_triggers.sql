    p_actor_ref VARCHAR(255),
    p_target_user_id BIGINT,
    p_target_email_snapshot VARCHAR(255),
    p_profile_before VARCHAR(16),
    p_profile_after VARCHAR(16),
    p_reason TEXT,
    p_change_ticket VARCHAR(128),
    p_request_id VARCHAR(128),
    p_error_code VARCHAR(64)
