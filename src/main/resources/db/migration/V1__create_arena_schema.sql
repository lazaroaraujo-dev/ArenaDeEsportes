CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    telefone VARCHAR(255) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    perfil VARCHAR(255) NOT NULL,
    CONSTRAINT uq_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_perfil
        CHECK (perfil IN ('ADMIN', 'CLIENTE'))
);

CREATE TABLE quadra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    tipo VARCHAR(255) NOT NULL,
    ativa BOOLEAN NOT NULL,
    CONSTRAINT ck_quadra_tipo
        CHECK (tipo IN ('FUTVOLEI', 'BEACH_TENNIS', 'VOLEI_AREIA'))
);

CREATE TABLE agendamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data DATE NOT NULL,
    hora_inicio TIME WITHOUT TIME ZONE NOT NULL,
    hora_fim TIME WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(255) NOT NULL DEFAULT 'PENDENTE',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),
    usuario_id BIGINT NOT NULL,
    quadra_id BIGINT NOT NULL,
    CONSTRAINT ck_agendamento_horario
        CHECK (hora_fim > hora_inicio),
    CONSTRAINT ck_agendamento_status
        CHECK (status IN ('PENDENTE', 'CONFIRMADO', 'CANCELADO', 'EXPIRADO')),
    CONSTRAINT fk_agendamento_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuario(id)
        ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT fk_agendamento_quadra
        FOREIGN KEY (quadra_id) REFERENCES quadra(id)
        ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT ex_agendamento_quadra_periodo_bloqueante
        EXCLUDE USING gist (
            quadra_id WITH =,
            (tsrange(data + hora_inicio, data + hora_fim, '[)')) WITH &&
        )
        WHERE (status IN ('PENDENTE', 'CONFIRMADO'))
);

CREATE INDEX ix_agendamento_usuario_id
    ON agendamento (usuario_id);

CREATE INDEX ix_agendamento_quadra_data
    ON agendamento (quadra_id, data);

CREATE INDEX ix_agendamento_pendente_criado_em
    ON agendamento (criado_em)
    WHERE status = 'PENDENTE';
